// Fluid type tokens: scans src for var(--fs-N) and writes src/app/type-tokens.css.
// Ramp: 360px phone -> 1280px desktop. Rules: <=15px +1 on phones, 16-20 same, >=22 x0.78.
// OVERRIDE holds the design system's own mobile sizes for display type (spec table in the PDF).
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';
import assert from 'node:assert';

const OVERRIDE = { 112: 44, 72: 38, 36: 26, 32: 24, 20: 18, 18: 16 };
const phone = (d) => OVERRIDE[d] ?? (d <= 15 ? d + 1 : d <= 20 ? d : Math.round(d * 0.78));
const r = (n) => +n.toFixed(4);
export function token(d) {
  const m = phone(d), slope = (d - m) / 920, intercept = m - slope * 360;
  if (!slope) return `${r(d / 16)}rem`;
  const sign = slope < 0 ? '-' : '+';
  return `clamp(${r(Math.min(m, d) / 16)}rem, ${r(intercept / 16)}rem ${sign} ${r(Math.abs(slope) * 100)}vw, ${r(Math.max(m, d) / 16)}rem)`;
}
assert.equal(token(16), '1rem');
assert.equal(token(13), 'clamp(0.8125rem, 0.8995rem - 0.1087vw, 0.875rem)');
assert.ok(token(112).startsWith('clamp(2.75rem'));

const walk = (dir) => readdirSync(dir).flatMap((f) => {
  const p = join(dir, f);
  return statSync(p).isDirectory() ? walk(p) : /\.(tsx?|css)$/.test(f) && f !== 'type-tokens.css' ? [p] : [];
});
const sizes = new Set();
for (const file of walk('src')) for (const m of readFileSync(file, 'utf8').matchAll(/--fs-(\d+(?:-\d)?)\b/g)) sizes.add(m[1]);
const lines = [...sizes].map((s) => [s, parseFloat(s.replace('-', '.'))]).sort((a, b) => a[1] - b[1])
  .map(([name, d]) => `  --fs-${name}: ${token(d)};`);
writeFileSync('src/app/type-tokens.css', `/* Generated by scripts/fluid-type.mjs. Do not edit by hand. */\n:root {\n${lines.join('\n')}\n}\n`);
console.log(lines.join('\n'));
